import { writeFileSync } from 'node:fs';
import { launch, sleep } from './cdp.mjs';
const W = process.argv[2];
const b = await launch({ profile: W + '/prof-rain', port: 9515 });
await b.send('Page.enable'); await b.send('Runtime.enable');
await b.send('Emulation.setDeviceMetricsOverride', { width: 1600, height: 900, deviceScaleFactor: 1, mobile: false });
await b.send('Page.navigate', { url: 'file:///D:/angles%20learning%20section/index.html?s=6&novo' });
for (let i = 0; i < 80 && !(await b.ev(`typeof UI !== 'undefined'`).catch(() => false)); i++) await sleep(100);
await sleep(5000);
// frame-rate probe across the whole rain
await b.ev(`(() => { window.__f = []; let last = performance.now(); const loop = t => { window.__f.push(t - last); last = t; if (window.__f.length < 400) requestAnimationFrame(loop); }; requestAnimationFrame(loop); UI.correct(); })()`);
await sleep(1200);
const r = await b.send('Page.captureScreenshot', { format: 'png' }); writeFileSync(`${W}/rain.png`, Buffer.from(r.result.data, 'base64'));
const mid = await b.ev(`document.querySelectorAll('.fall .fa').length`);
await sleep(4200);
const f = await b.ev(`window.__f.slice(1)`);
const left = await b.ev(`document.querySelectorAll('.fall .fa').length`);
const avg = f.reduce((a, x) => a + x, 0) / f.length, sorted = [...f].sort((a, b) => a - b);
console.log(`pieces mid-rain ${mid} · after ${left} · frames ${f.length} · avg ${avg.toFixed(1)} ms (${(1000 / avg).toFixed(0)} fps) · p95 ${sorted[Math.floor(f.length * .95)].toFixed(1)} ms · worst ${sorted.at(-1).toFixed(1)} ms`);
await b.ev(`UI.correct({ small: true })`); await sleep(1300); await b.ev(`UI.correct({ small: true })`);
console.log('partial-answer rain pieces:', await b.ev(`document.querySelectorAll('.fall .fa').length`));
b.close(); process.exit(0);
