import { writeFileSync } from 'node:fs';
import { launch, sleep } from './cdp.mjs';
const W = process.argv[2];
const b = await launch({ profile: W + '/prof-sad', port: 9521 });
await b.send('Page.enable'); await b.send('Runtime.enable');
await b.send('Emulation.setDeviceMetricsOverride', { width: 1600, height: 900, deviceScaleFactor: 1, mobile: false });
const errs = []; b.on('Runtime.exceptionThrown', p => errs.push(p.exceptionDetails.exception?.description));
const shot = async n => { const r = await b.send('Page.captureScreenshot', { format: 'png' }); writeFileSync(`${W}/${n}.png`, Buffer.from(r.result.data, 'base64')); };
await b.send('Page.navigate', { url: 'file:///D:/angles%20learning%20section/index.html?s=4&novo' });
for (let i = 0; i < 80 && !(await b.ev(`typeof UI !== 'undefined'`).catch(() => false)); i++) await sleep(100);
await sleep(6000);
await b.ev(`(() => { window.__plays = []; const P = HTMLMediaElement.prototype.play; HTMLMediaElement.prototype.play = function () { window.__plays.push(this.src.split('/').pop()); return P.call(this); }; })()`);
await b.ev(`UI.incorrect()`);
await sleep(230); await shot('sad_1');
await sleep(620); await shot('sad_2');
const mid = await b.ev(`({ pieces: document.querySelectorAll('.sadface .sp').length, blocks: getComputedStyle(document.querySelector('.sadface')).pointerEvents, plays: window.__plays, hit: document.elementFromPoint(800, 470).closest('.sadface') ? 'face blocks' : 'passes through' })`);
await sleep(1100);
const end = await b.ev(`({ pieces: document.querySelectorAll('.sadface .sp').length, on: document.querySelector('.sadface').classList.contains('on') })`);
console.log('formed:', JSON.stringify(mid), '| after 1.9 s:', JSON.stringify(end), '| errors:', errs);
b.close(); process.exit(0);
