import { writeFileSync } from 'node:fs';
import { launch, sleep } from './cdp.mjs';
const W = process.argv[2];
const b = await launch({ profile: W + '/prof-sad3', port: 9523 });
await b.send('Page.enable');
await b.send('Emulation.setDeviceMetricsOverride', { width: 1600, height: 900, deviceScaleFactor: 1, mobile: false });
await b.send('Page.navigate', { url: `file:///D:/angles%20learning%20section/index.html?s=${process.argv[3] || 4}&novo` });
for (let i = 0; i < 80 && !(await b.ev(`typeof UI !== 'undefined'`).catch(() => false)); i++) await sleep(100);
await sleep(5000);
await b.ev(`(() => { UI.incorrect(); const s = document.querySelector('.sadface'); clearTimeout(s._t1); clearTimeout(s._t2);
  s.getAnimations({ subtree: true }).forEach(a => { a.pause(); a.currentTime = 1100; }); })()`);
await sleep(400);
const r = await b.send('Page.captureScreenshot', { format: 'png', clip: { x: 560, y: 230, width: 480, height: 480, scale: 1 } });
writeFileSync(`${W}/sad_formed.png`, Buffer.from(r.result.data, 'base64'));
b.close(); process.exit(0);
